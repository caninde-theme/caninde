#!/usr/bin/env node
// Reads tokens/, generates every artifact. Run with `npm run build`.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTokens } from './lib/load.mjs';
import { renderRolesDoc } from './lib/docs.mjs';
import * as vscode from './targets/vscode.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));

// Register new app targets here (see docs/PORTING.md).
const targets = [vscode];

const { essence, rolesDoc, palette, variants } = await loadTokens(root);

const files = new Map();

files.set(
  'tokens/palette.json',
  JSON.stringify(
    {
      $generated: 'DO NOT EDIT. Generated by `npm run build` from tokens/essence.json.',
      ...palette,
    },
    null,
    2,
  ) + '\n',
);

files.set('docs/ROLES.md', renderRolesDoc({ rolesDoc, variants }));

for (const [variantId, variant] of Object.entries(variants)) {
  for (const target of targets) {
    const output = await target.build({ root, essence, palette, variantId, variant });
    for (const file of output) files.set(file.path, file.content);
  }
}

for (const [rel, content] of files) {
  const abs = join(root, rel);
  await mkdir(dirname(abs), { recursive: true });
  await writeFile(abs, content);
  console.log(`  wrote ${rel}`);
}

console.log(`\n${essence.name} built: ${files.size} files, ${Object.keys(variants).length} variant(s).`);
